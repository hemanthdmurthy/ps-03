@asynccontextmanager
async def get_async_db_session():
    """Async context manager for non-blocking database transactions with auto-commit/rollback."""
    async with AsyncSessionLocal() as session:
        try:
            yield session
            await session.commit()
        except Exception as e:
            await session.rollback()
            logger.error(f"Async database transaction error, rollback executed: {e}")
            raise
        finally:
            await session.close()


