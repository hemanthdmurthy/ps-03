def to_dict(model_instance) -> Dict[str, Any]:
    """Helper to convert SQLAlchemy model instance to clean dictionary."""
    if not model_instance:
        return {}
    res = {}
    for column in model_instance.__table__.columns:
        val = getattr(model_instance, column.name)
        if isinstance(val, datetime):
            res[column.name] = val.isoformat()
        else:
            res[column.name] = val
    return res

def company_to_dict(company_instance) -> Dict[str, Any]:
    """Helper to serialize StagingCompany with backward-compatible aliases."""
    if not company_instance:
        return {}
    res = to_dict(company_instance)
    res["staging_id"] = company_instance.company_id  # Map alias
    return res


class SupabaseService:
    """
    Decoupled database service class interacting with SQLAlchemy ORM.
    Acts as a direct drop-in replacement for the previous Supabase REST API client.
    
    Provides both synchronous methods (for Celery workers / sync contexts) and
    async methods (prefixed with 'a') for FastAPI route handlers.
    """
    _instance = None

    def __new__(cls, *args, **kwargs):
        if not cls._instance:
            cls._instance = super(SupabaseService, cls).__new__(cls, *args, **kwargs)
        return cls._instance

