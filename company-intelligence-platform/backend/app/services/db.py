@contextmanager
def get_db_session():
    """Context manager for thread-safe database transactions."""
    db = SessionLocal()
    try:
        yield db
        db.commit()
    except Exception as e:
        db.rollback()
        logger.error(f"Database transaction error, rollback executed: {e}")
        raise
    finally:
        db.close()


