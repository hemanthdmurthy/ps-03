    def test_connection(self) -> bool:
        """Runs a quick lightweight query to verify database accessibility."""
        try:
            with get_db_session() as db:
                db.execute(text("SELECT 1"))
                return True
        except Exception as e:
            logger.error(f"Database connectivity test failed: {e}")
            return False

    def create_session(self, company_name: str, industry: Optional[str] = None, custom_query: Optional[str] = None) -> Dict[str, Any]:
        """Creates a new research session row in database."""
        with get_db_session() as db:
            session = ResearchSession(
                company_name=company_name,
                industry=industry,
                custom_query=custom_query,
                status="initiated",
                confidence_score=0.0
            )
            db.add(session)
            db.flush()  # Populates autogenerated ID field
            return to_dict(session)

    def update_session(self, session_id: str, updates: Dict[str, Any]) -> Dict[str, Any]:
        """Updates research session properties."""
        with get_db_session() as db:
            session = db.query(ResearchSession).filter(ResearchSession.id == session_id).first()
            if not session:
                logger.warning(f"Failed to find session to update: {session_id}")
                return {}

            for k, v in updates.items():
                if hasattr(session, k):
                    setattr(session, k, v)
            db.flush()
            return to_dict(session)

    def get_session(self, session_id: str) -> Optional[Dict[str, Any]]:
        """Fetches a research session by ID."""
        with get_db_session() as db:
            session = db.query(ResearchSession).filter(ResearchSession.id == session_id).first()
            return to_dict(session) if session else None

