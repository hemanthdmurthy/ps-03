    def get_company_by_name(self, name: str) -> Optional[Dict[str, Any]]:
        """Queries staging_company for an exact or case-insensitive matching company name."""
        clean_name = name.strip()
        with get_db_session() as db:
            # First attempt: Exact match
            company = db.query(StagingCompany).filter(StagingCompany.name == clean_name).first()
            if company:
                return company_to_dict(company)

            # Second attempt: Case-insensitive SQL LIKE search
            company_ilike = db.query(StagingCompany).filter(StagingCompany.name.ilike(f"%{clean_name}%")).first()
            return company_to_dict(company_ilike) if company_ilike else None

    def get_final_report_by_company_name(self, name: str) -> Optional[Dict[str, Any]]:
        """Queries for the latest finalized brief report for a given company name."""
        clean_name = name.strip()
        with get_db_session() as db:
            # First attempt: Exact match
            report = db.query(FinalReport).filter(
                FinalReport.company_name == clean_name
            ).order_by(FinalReport.created_at.desc()).first()
            if report:
                return to_dict(report)

            # Second attempt: SQL LIKE search
            report_ilike = db.query(FinalReport).filter(
                FinalReport.company_name.ilike(f"%{clean_name}%")
            ).order_by(FinalReport.created_at.desc()).first()
            return to_dict(report_ilike) if report_ilike else None

    def upsert_company(self, company_data: Dict[str, Any]) -> Dict[str, Any]:
        """Upserts a company record in the local staging_company database table."""
        company_name = company_data.get("name")
        if not company_name:
            raise ValueError("Company data must contain a 'name' field for upsert operations.")

        with get_db_session() as db:
            company = db.query(StagingCompany).filter(StagingCompany.name == company_name).first()

            # Filter payload keys to protect primary key fields and prevent database issues
            payload = {k: v for k, v in company_data.items() if k not in ["staging_id", "company_id", "inserted_at"]}

            if company:
                for k, v in payload.items():
                    if hasattr(company, k):
                        setattr(company, k, v)
            else:
                company = StagingCompany(**company_data)
                db.add(company)

            db.flush()
            return company_to_dict(company)

