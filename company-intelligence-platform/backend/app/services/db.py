                total_tokens = sum(l.total_tokens for l in logs)
                total_cost = sum(l.estimated_cost for l in logs)

                # Models usage aggregation
                models = {}
                for l in logs:
                    if l.model_name:
                        models[l.model_name] = models.get(l.model_name, 0) + l.total_tokens

